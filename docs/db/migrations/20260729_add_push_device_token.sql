CREATE TABLE PUSH_DEVICE_TOKEN (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_USER_ID BIGINT NOT NULL,
    PLATFORM VARCHAR(30) NOT NULL,
    DEVICE_TOKEN VARCHAR(512) NOT NULL,
    APP_VERSION VARCHAR(50) NULL,
    DEVICE_NAME VARCHAR(100) NULL,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    LAST_REGISTERED_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NULL,
    CONSTRAINT UK_PUSH_DEVICE_TOKEN_OWNER_TOKEN UNIQUE (OWNER_USER_ID, DEVICE_TOKEN),
    CONSTRAINT FK_PUSH_DEVICE_TOKEN_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID)
);

CREATE INDEX IDX_PUSH_DEVICE_TOKEN_OWNER_ACTIVE
    ON PUSH_DEVICE_TOKEN (OWNER_USER_ID, ACTIVE, LAST_REGISTERED_AT);
