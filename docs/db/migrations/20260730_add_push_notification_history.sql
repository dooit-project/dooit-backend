CREATE TABLE PUSH_NOTIFICATION_HISTORY (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_USER_ID BIGINT NOT NULL,
    PUSH_DEVICE_TOKEN_ID BIGINT NULL,
    SOURCE VARCHAR(30) NOT NULL,
    PROVIDER VARCHAR(30) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    TASK_ID BIGINT NULL,
    RECURRENCE_SERIES_ID BIGINT NULL,
    OCCURRENCE_DATE DATE NULL,
    NOTIFICATION_KEY VARCHAR(120) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR(160) NOT NULL,
    PROVIDER_MESSAGE_ID VARCHAR(160) NULL,
    ERROR_CODE VARCHAR(120) NULL,
    ERROR_MESSAGE VARCHAR(500) NULL,
    ATTEMPTED_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_PUSH_NOTIFICATION_HISTORY_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_PUSH_NOTIFICATION_HISTORY_TOKEN FOREIGN KEY (PUSH_DEVICE_TOKEN_ID) REFERENCES PUSH_DEVICE_TOKEN(ID)
);

CREATE INDEX IDX_PUSH_NOTIFICATION_HISTORY_OWNER_ATTEMPTED
    ON PUSH_NOTIFICATION_HISTORY (OWNER_USER_ID, ATTEMPTED_AT, ID);

CREATE INDEX IDX_PUSH_NOTIFICATION_HISTORY_OWNER_IDEMPOTENCY_STATUS
    ON PUSH_NOTIFICATION_HISTORY (OWNER_USER_ID, IDEMPOTENCY_KEY, STATUS);
