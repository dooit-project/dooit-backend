-- Personal system, occurrence, practice evidence tables.

CREATE TABLE PERSONAL_SYSTEM (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    OWNER_USER_ID BIGINT NOT NULL,
    CURRENT_VERSION INT NOT NULL DEFAULT 1,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    LINKED_DDAY_GOAL_ID BIGINT NULL,
    ARCHIVED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT FK_PERSONAL_SYSTEM_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_PERSONAL_SYSTEM_DDAY FOREIGN KEY (LINKED_DDAY_GOAL_ID) REFERENCES DDAY_GOAL(ID)
);

CREATE INDEX IDX_PERSONAL_SYSTEM_OWNER_STATUS
    ON PERSONAL_SYSTEM (OWNER_USER_ID, STATUS, ID);

CREATE TABLE PERSONAL_SYSTEM_VERSION (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    SYSTEM_ID BIGINT NOT NULL,
    VERSION INT NOT NULL,
    DIRECTION_TEXT VARCHAR(500) NOT NULL,
    MOTIVATION_TEXT VARCHAR(500) NULL,
    TRIGGER_TEXT VARCHAR(200) NOT NULL,
    SCHEDULE_START_DATE DATE NOT NULL,
    SCHEDULE_DAYS VARCHAR(30) NOT NULL,
    SCHEDULE_TIME_ZONE VARCHAR(50) NOT NULL,
    NOTIFY_AT_TIME TIME NULL,
    STANDARD_ACTION_TEXT VARCHAR(500) NOT NULL,
    STANDARD_TARGET_AMOUNT VARCHAR(100) NULL,
    STANDARD_ESTIMATED_MINUTES INT NULL,
    MINIMUM_ACTION_TEXT VARCHAR(500) NOT NULL,
    MINIMUM_TARGET_AMOUNT VARCHAR(100) NULL,
    MINIMUM_ESTIMATED_MINUTES INT NULL,
    NEXT_ACTION VARCHAR(300) NULL,
    EFFECTIVE_FROM_DATE DATE NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_PERSONAL_SYSTEM_VERSION UNIQUE (SYSTEM_ID, VERSION),
    CONSTRAINT FK_PERSONAL_SYSTEM_VERSION_SYSTEM FOREIGN KEY (SYSTEM_ID) REFERENCES PERSONAL_SYSTEM(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_PERSONAL_SYSTEM_VERSION_EFFECTIVE
    ON PERSONAL_SYSTEM_VERSION (SYSTEM_ID, EFFECTIVE_FROM_DATE, VERSION);

CREATE TABLE PERSONAL_SYSTEM_OCCURRENCE (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    SYSTEM_ID BIGINT NOT NULL,
    SYSTEM_VERSION INT NOT NULL,
    OWNER_USER_ID BIGINT NOT NULL,
    SERVICE_DATE DATE NOT NULL,
    TIME_ZONE VARCHAR(50) NOT NULL,
    SNAPSHOT_DIRECTION_TEXT VARCHAR(500) NOT NULL,
    SNAPSHOT_TRIGGER_TEXT VARCHAR(200) NOT NULL,
    SNAPSHOT_STANDARD_ACTION_TEXT VARCHAR(500) NOT NULL,
    SNAPSHOT_MINIMUM_ACTION_TEXT VARCHAR(500) NOT NULL,
    SNAPSHOT_NEXT_ACTION VARCHAR(300) NULL,
    SNAPSHOT_NOTIFY_AT_TIME TIME NULL,
    LINKED_TASK_ID BIGINT NULL,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    ENTITY_VERSION BIGINT NOT NULL DEFAULT 0,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_PERSONAL_SYSTEM_OCCURRENCE_DATE UNIQUE (SYSTEM_ID, SERVICE_DATE),
    CONSTRAINT FK_PERSONAL_SYSTEM_OCCURRENCE_SYSTEM FOREIGN KEY (SYSTEM_ID) REFERENCES PERSONAL_SYSTEM(ID),
    CONSTRAINT FK_PERSONAL_SYSTEM_OCCURRENCE_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_PERSONAL_SYSTEM_OCCURRENCE_TASK FOREIGN KEY (LINKED_TASK_ID) REFERENCES TASK(ID)
);

CREATE INDEX IDX_PERSONAL_SYSTEM_OCCURRENCE_OWNER_DATE
    ON PERSONAL_SYSTEM_OCCURRENCE (OWNER_USER_ID, SERVICE_DATE, ID);

CREATE TABLE PERSONAL_SYSTEM_PRACTICE_RESULT (
    OCCURRENCE_ID BIGINT NOT NULL,
    ACTION_VARIANT VARCHAR(30) NOT NULL,
    PRACTICED_AT DATETIME NOT NULL,
    PRACTICED_TIME_ZONE VARCHAR(50) NOT NULL,
    ACCOMPLISHED_NOTE VARCHAR(1000) NULL,
    DIFFICULTIES VARCHAR(200) NULL,
    NEXT_ACTION_PATCH_KIND VARCHAR(30) NOT NULL DEFAULT 'KEEP',
    NEXT_ACTION_VALUE VARCHAR(300) NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (OCCURRENCE_ID),
    CONSTRAINT FK_PERSONAL_SYSTEM_RESULT_OCCURRENCE FOREIGN KEY (OCCURRENCE_ID) REFERENCES PERSONAL_SYSTEM_OCCURRENCE(ID) ON DELETE CASCADE
);
