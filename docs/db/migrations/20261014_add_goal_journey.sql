-- Goal journey tables.
-- Apply manually to production DB after backup verification.

START TRANSACTION;

CREATE TABLE GOAL (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    OWNER_USER_ID BIGINT NOT NULL,
    TITLE VARCHAR(120) NOT NULL,
    DESIRED_OUTCOME VARCHAR(500) NULL,
    MOTIVATION_TEXT VARCHAR(500) NULL,
    TARGET_DATE DATE NULL,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    CURRENT_VERSION INT NOT NULL DEFAULT 1,
    LINKED_DDAY_GOAL_ID BIGINT NULL,
    ACHIEVED_AT DATETIME NULL,
    ARCHIVED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT FK_GOAL_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_GOAL_DDAY FOREIGN KEY (LINKED_DDAY_GOAL_ID) REFERENCES DDAY_GOAL(ID)
);

CREATE INDEX IDX_GOAL_OWNER_STATUS
    ON GOAL (OWNER_USER_ID, STATUS, ID);

CREATE INDEX IDX_GOAL_OWNER_TARGET_DATE
    ON GOAL (OWNER_USER_ID, TARGET_DATE, ID);

CREATE TABLE GOAL_VERSION (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    GOAL_ID BIGINT NOT NULL,
    VERSION INT NOT NULL,
    TITLE VARCHAR(120) NOT NULL,
    DESIRED_OUTCOME VARCHAR(500) NULL,
    MOTIVATION_TEXT VARCHAR(500) NULL,
    TARGET_DATE DATE NULL,
    EFFECTIVE_FROM_DATE DATE NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_GOAL_VERSION UNIQUE (GOAL_ID, VERSION),
    CONSTRAINT FK_GOAL_VERSION_GOAL FOREIGN KEY (GOAL_ID) REFERENCES GOAL(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_GOAL_VERSION_EFFECTIVE
    ON GOAL_VERSION (GOAL_ID, EFFECTIVE_FROM_DATE, VERSION);

CREATE TABLE GOAL_PLAN (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    OWNER_USER_ID BIGINT NOT NULL,
    GOAL_ID BIGINT NULL,
    CURRENT_VERSION INT NOT NULL DEFAULT 1,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    ARCHIVED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT FK_GOAL_PLAN_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_GOAL_PLAN_GOAL FOREIGN KEY (GOAL_ID) REFERENCES GOAL(ID)
);

CREATE INDEX IDX_GOAL_PLAN_OWNER_STATUS
    ON GOAL_PLAN (OWNER_USER_ID, STATUS, ID);

CREATE INDEX IDX_GOAL_PLAN_GOAL_STATUS
    ON GOAL_PLAN (GOAL_ID, STATUS, ID);

CREATE TABLE GOAL_PLAN_VERSION (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    PLAN_ID BIGINT NOT NULL,
    VERSION INT NOT NULL,
    GOAL_ID BIGINT NULL,
    NAME VARCHAR(120) NOT NULL,
    TRIGGER_TEXT VARCHAR(200) NULL,
    SCHEDULE_START_DATE DATE NOT NULL,
    SCHEDULE_DAYS VARCHAR(30) NOT NULL,
    SCHEDULE_TIME_ZONE VARCHAR(50) NOT NULL,
    NOTIFY_AT_TIME TIME NULL,
    STANDARD_ACTION_TEXT VARCHAR(500) NOT NULL,
    STANDARD_TARGET_AMOUNT VARCHAR(100) NULL,
    STANDARD_ESTIMATED_MINUTES INT NULL,
    MINIMUM_ACTION_TEXT VARCHAR(500) NOT NULL,
    MINIMUM_TARGET_AMOUNT VARCHAR(100) NULL,
    MINIMUM_ESTIMATED_MINUTES INT NULL,
    NEXT_ACTION VARCHAR(300) NULL,
    EFFECTIVE_FROM_DATE DATE NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_GOAL_PLAN_VERSION UNIQUE (PLAN_ID, VERSION),
    CONSTRAINT FK_GOAL_PLAN_VERSION_PLAN FOREIGN KEY (PLAN_ID) REFERENCES GOAL_PLAN(ID) ON DELETE CASCADE,
    CONSTRAINT FK_GOAL_PLAN_VERSION_GOAL FOREIGN KEY (GOAL_ID) REFERENCES GOAL(ID)
);

CREATE INDEX IDX_GOAL_PLAN_VERSION_EFFECTIVE
    ON GOAL_PLAN_VERSION (PLAN_ID, EFFECTIVE_FROM_DATE, VERSION);

CREATE TABLE GOAL_PLAN_OCCURRENCE (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    OWNER_USER_ID BIGINT NOT NULL,
    GOAL_ID BIGINT NULL,
    GOAL_VERSION INT NULL,
    PLAN_ID BIGINT NOT NULL,
    PLAN_VERSION INT NOT NULL,
    SERVICE_DATE DATE NOT NULL,
    TIME_ZONE VARCHAR(50) NOT NULL,
    SNAPSHOT_GOAL_TITLE VARCHAR(120) NULL,
    SNAPSHOT_PLAN_NAME VARCHAR(120) NOT NULL,
    SNAPSHOT_TRIGGER_TEXT VARCHAR(200) NULL,
    SNAPSHOT_STANDARD_ACTION_TEXT VARCHAR(500) NOT NULL,
    SNAPSHOT_MINIMUM_ACTION_TEXT VARCHAR(500) NOT NULL,
    SNAPSHOT_NEXT_ACTION VARCHAR(300) NULL,
    SNAPSHOT_NOTIFY_AT_TIME TIME NULL,
    LINKED_TASK_ID BIGINT NULL,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    ENTITY_VERSION BIGINT NOT NULL DEFAULT 0,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_GOAL_PLAN_OCCURRENCE_DATE UNIQUE (PLAN_ID, SERVICE_DATE),
    CONSTRAINT FK_GOAL_OCCURRENCE_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_GOAL_OCCURRENCE_GOAL FOREIGN KEY (GOAL_ID) REFERENCES GOAL(ID),
    CONSTRAINT FK_GOAL_OCCURRENCE_PLAN FOREIGN KEY (PLAN_ID) REFERENCES GOAL_PLAN(ID),
    CONSTRAINT FK_GOAL_OCCURRENCE_TASK FOREIGN KEY (LINKED_TASK_ID) REFERENCES TASK(ID)
);

CREATE INDEX IDX_GOAL_OCCURRENCE_OWNER_DATE
    ON GOAL_PLAN_OCCURRENCE (OWNER_USER_ID, SERVICE_DATE, ID);

CREATE INDEX IDX_GOAL_OCCURRENCE_GOAL_DATE
    ON GOAL_PLAN_OCCURRENCE (GOAL_ID, SERVICE_DATE, ID);

CREATE TABLE GOAL_PRACTICE_RESULT (
    OCCURRENCE_ID BIGINT NOT NULL,
    ACTION_VARIANT VARCHAR(30) NOT NULL,
    PRACTICED_AT DATETIME NOT NULL,
    PRACTICED_TIME_ZONE VARCHAR(50) NOT NULL,
    ACCOMPLISHED_NOTE VARCHAR(1000) NULL,
    DIFFICULTIES VARCHAR(200) NULL,
    NEXT_ACTION_PATCH_KIND VARCHAR(30) NOT NULL DEFAULT 'KEEP',
    NEXT_ACTION_VALUE VARCHAR(300) NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    PRIMARY KEY (OCCURRENCE_ID),
    CONSTRAINT FK_GOAL_RESULT_OCCURRENCE FOREIGN KEY (OCCURRENCE_ID) REFERENCES GOAL_PLAN_OCCURRENCE(ID) ON DELETE CASCADE
);

CREATE TABLE GOAL_DIRECT_LOG (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    OWNER_USER_ID BIGINT NOT NULL,
    GOAL_ID BIGINT NOT NULL,
    GOAL_VERSION INT NOT NULL,
    PRACTICED_DATE DATE NOT NULL,
    PRACTICED_TIME_ZONE VARCHAR(50) NOT NULL,
    TITLE VARCHAR(120) NOT NULL,
    NOTE VARCHAR(1000) NULL,
    IDEMPOTENCY_KEY VARCHAR(160) NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NULL,
    CANCELED_AT DATETIME NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_GOAL_DIRECT_LOG_IDEMPOTENCY UNIQUE (OWNER_USER_ID, GOAL_ID, IDEMPOTENCY_KEY),
    CONSTRAINT FK_GOAL_DIRECT_LOG_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USER(ID),
    CONSTRAINT FK_GOAL_DIRECT_LOG_GOAL FOREIGN KEY (GOAL_ID) REFERENCES GOAL(ID)
);

CREATE INDEX IDX_GOAL_DIRECT_LOG_GOAL_DATE
    ON GOAL_DIRECT_LOG (GOAL_ID, PRACTICED_DATE, ID);

ALTER TABLE TASK
    ADD COLUMN LINKED_GOAL_ID BIGINT NULL,
    ADD CONSTRAINT FK_TASK_LINKED_GOAL FOREIGN KEY (LINKED_GOAL_ID) REFERENCES GOAL(ID);

CREATE INDEX IDX_TASK_LINKED_GOAL_COMPLETED
    ON TASK (LINKED_GOAL_ID, COMPLETED_AT, ID);

COMMIT;
